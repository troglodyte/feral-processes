def write_png(path, pixels):
    """pixels: SIZE rows of SIZE (r, g, b, a) byte tuples."""

    def chunk(tag, data):
        body = tag + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))

    raw = b"".join(b"\x00" + bytes(c for px in row for c in px) for row in pixels)
    png = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )
    path.write_bytes(png)


def pixels(rows):
    assert len(rows) == SIZE and all(len(r) == SIZE for r in rows), rows
    return [
        [(0, 0, 0, 0) if c == "." else (int(c, 16) * 17,) * 3 + (255,) for c in row]
        for row in rows
    ]


def main():
    force = "--force" in sys.argv[1:]
    for name, rows in SPRITES.items():
        path = OUT / f"{name}.png"
        if path.exists() and not force:
            print(f"skip {path.name} (exists; --force to overwrite)")
            continue
        write_png(path, pixels(rows))
        print(f"wrote {path.name}")


if __name__ == "__main__":
    main()
